export type Locale = "zh" | "en";
export type Translate = (
  key: Message,
  values?: Record<string, string | number>,
) => string;
export const translator =
  (locale: Locale): Translate =>
  (key, values = {}) =>
    (locale === "zh" ? zh : en)[key].replace(/\{(\w+)\}/g, (match, name) =>
      String(values[name] ?? match),
    );
